#!/usr/bin/env python3
"""Build/check the checked-in catalogue registry coverage matrix."""

from __future__ import annotations

import argparse
import json
from collections import Counter, defaultdict
from pathlib import Path

from tools.markdown import normalize_markdown

ROOT = Path(__file__).resolve().parents[2]
CATALOGUE = ROOT / "src/funcprops/data/catalogue.json"
CAPABILITIES = ROOT / "src/funcprops/data/registry_capabilities.json"
BASELINE = ROOT / ".github/registry/coverage-baseline.json"
MATRIX = ROOT / ".github/registry/coverage-matrix.md"


def snapshot():
    from funcprops.native_registry import native_registry_snapshot

    families = json.loads(CATALOGUE.read_text())["families"]
    categories = defaultdict(Counter)
    totals = Counter()
    for fam in families:
        category = fam.get("category") or "uncategorized"
        for prop in fam.get("properties", {}):
            categories[category][prop] += 1
            totals[prop] += 1
    return {
        "family_count": len(families),
        "categories": {
            k: dict(sorted(v.items())) for k, v in sorted(categories.items())
        },
        "property_totals": dict(sorted(totals.items())),
        "native_capabilities": json.loads(CAPABILITIES.read_text()),
        "native_registry": native_registry_snapshot(),
    }


def markdown(data):
    props = sorted(data["property_totals"])
    lines = [
        "# Registry coverage matrix",
        "",
        "Generated by `tools/registry_coverage/coverage_matrix.py`. Cells are the number of",
        "catalogue families in each category carrying that property. CI compares the JSON",
        "baseline monotonically: an existing cell/count may grow but may not shrink silently.",
        "",
        f"Families: **{data['family_count']}**; properties: **{len(props)}**.",
        "",
        "| Category | " + " | ".join(props) + " |",
        "|---|" + "|".join("---:" for _ in props) + "|",
    ]
    for category, counts in data["categories"].items():
        lines.append(
            "| "
            + category
            + " | "
            + " | ".join(str(counts.get(p, 0)) for p in props)
            + " |"
        )
    lines += ["", "## Property totals", "", "| Property | Families |", "|---|---:|"]
    lines += [f"| {p} | {data['property_totals'][p]} |" for p in props]
    native = data["native_registry"]
    lines += [
        "",
        "## Native theorem coverage",
        "",
        f"Native families: **{native['family_count']}**.",
        "",
    ]
    lines += ["Families: " + ", ".join(native["families"]) + ".", ""]
    lines += ["| Native property | Rules |", "|---|---:|"]
    lines += [f"| {p} | {n} |" for p, n in native["property_rule_counts"].items()]
    lines += [
        "",
        "Derivative slots: "
        + "; ".join(
            f"{f}: {positions}"
            for f, positions in native["derivative_positions"].items()
        )
        + ".",
        "",
    ]
    caps = data["native_capabilities"]
    lines += ["", "## Native registry capabilities", ""]
    lines += ["Rule types: " + ", ".join(caps["native_rule_types"]) + ".", ""]
    lines += ["Certificates: " + ", ".join(caps["certificates"]) + ".", ""]
    lines += ["| Transport mode | Certified property shapes |", "|---|---|"]
    for mode, values in sorted(caps["transport"].items()):
        lines.append(f"| {mode} | {', '.join(values)} |")
    piecewise = caps.get("piecewise", {})
    if piecewise:
        lines += [
            "",
            "## Piecewise coverage",
            "",
            "| Layer | Certified capabilities |",
            "|---|---|",
        ]
        for layer, values in sorted(piecewise.items()):
            lines.append(f"| {layer} | {', '.join(values)} |")
    return normalize_markdown("\n".join(lines))


def regressions(old, new):
    out = []
    if new["family_count"] < old["family_count"]:
        out.append(f"family_count: {old['family_count']} -> {new['family_count']}")
    for category, counts in old["categories"].items():
        current = new["categories"].get(category, {})
        for prop, count in counts.items():
            if current.get(prop, 0) < count:
                out.append(f"{category}/{prop}: {count} -> {current.get(prop, 0)}")

    old_native = old.get("native_registry", {})
    new_native = new.get("native_registry", {})
    if new_native.get("family_count", 0) < old_native.get("family_count", 0):
        out.append(
            f"native_registry/family_count: {old_native.get('family_count', 0)} -> {new_native.get('family_count', 0)}"
        )
    for family in old_native.get("families", ()):
        if family not in new_native.get("families", ()):
            out.append(f"native_registry/families: removed {family}")
    for prop, count in old_native.get("property_rule_counts", {}).items():
        current = new_native.get("property_rule_counts", {}).get(prop, 0)
        if current < count:
            out.append(f"native_registry/property/{prop}: {count} -> {current}")
    for family, positions in old_native.get("derivative_positions", {}).items():
        current = set(new_native.get("derivative_positions", {}).get(family, ()))
        for position in positions:
            if position not in current:
                out.append(
                    f"native_registry/derivative/{family}: removed slot {position}"
                )
    for family, count in old_native.get("identity_rule_counts", {}).items():
        current = new_native.get("identity_rule_counts", {}).get(family, 0)
        if current < count:
            out.append(f"native_registry/identity/{family}: {count} -> {current}")

    old_caps = old.get("native_capabilities", {})
    new_caps = new.get("native_capabilities", {})
    for key in ("native_rule_types", "certificates"):
        missing = sorted(set(old_caps.get(key, ())) - set(new_caps.get(key, ())))
        for value in missing:
            out.append(f"native_capabilities/{key}: removed {value}")
    for mode, values in old_caps.get("transport", {}).items():
        current = set(new_caps.get("transport", {}).get(mode, ()))
        for value in sorted(set(values) - current):
            out.append(f"native_capabilities/transport/{mode}: removed {value}")
    for layer, values in old_caps.get("piecewise", {}).items():
        current = set(new_caps.get("piecewise", {}).get(layer, ()))
        for value in sorted(set(values) - current):
            out.append(f"native_capabilities/piecewise/{layer}: removed {value}")
    return out


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--update", action="store_true")
    ap.add_argument("--check", action="store_true")
    args = ap.parse_args()
    data = snapshot()
    if args.update:
        BASELINE.write_text(json.dumps(data, indent=2, sort_keys=True) + "\n")
        MATRIX.write_text(markdown(data))
    if args.check:
        old = json.loads(BASELINE.read_text())
        bad = regressions(old, data)
        if bad:
            raise SystemExit("Registry coverage regressed:\n  " + "\n  ".join(bad))
        expected = markdown(data)
        if MATRIX.read_text() != expected:
            raise SystemExit(
                "Registry coverage matrix is stale; run coverage_matrix.py --update"
            )
        print(
            f"registry coverage OK: {data['family_count']} families, {len(data['property_totals'])} properties"
        )


if __name__ == "__main__":
    main()
